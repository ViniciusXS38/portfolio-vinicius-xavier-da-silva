def simulador():
  locais = ["Quarto", "Corredor", "Sala", "Cozinha", "Saída"]
  estados = ["chave", "livre", "porta trancada", "livre", "livre"]
  pos = 0
  energia = 8
  chave = False
  while energia > 0:
    print("\nLocal atual:", locais[pos])
    estado = estados[pos]
    if estado == "chave":
      chave = True
      print("Pegou a chave")
    if estado == "porta trancada":
      if chave:
        print("Abriu a porta")
        pos += 1
      else:
        print("Porta trancada, voltando")
        pos -= 1
    else:
      print("Caminho livre")
      pos += 1
    if pos == len(locais) - 1:
      print("\nSaiu com sucesso!")
      break
    energia -= 1
  if energia <= 0:
    print("\nSem energia")
simulador()




