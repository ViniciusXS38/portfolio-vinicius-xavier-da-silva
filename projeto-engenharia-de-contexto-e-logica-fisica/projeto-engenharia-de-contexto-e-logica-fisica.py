def classificar_iqa(iqa):
  match iqa:
    case _ if iqa <= 50:
      return "Boa"
    case _ if iqa <= 100:
      return "Moderada"
    case _ if iqa <= 150:
      return "Ruim"
    case _:
      return "Muito Ruim"
def calcular_conforto(temp, umidade, iqa):
  nota = 10
  # penaliza temperatura longe de 25
  nota -= abs(temp - 25) * 0.2
  # ajuste da umidade
  if 40 <= umidade <= 70:
    nota += 1
  else:
    nota -= 1
  # penaliza poluição
  nota -= iqa * 0.03
  if nota < 0:
    nota = 0
  if nota > 10:
    nota = 10
  return round(nota, 2)
